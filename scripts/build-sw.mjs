// Post-build: writes public/sw.js with this build's precache list.
// Runs as part of `npm run build` (after `next build`).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const buildId = readFileSync(join(root, ".next", "BUILD_ID"), "utf8").trim();

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const toUrl = (base, file, prefix) => prefix + relative(base, file).split(sep).join("/");

const staticDir = join(root, ".next", "static");
const nextAssets = walk(staticDir).map((f) => toUrl(staticDir, f, "/_next/static/"));

const publicDir = join(root, "public");
const publicAssets = walk(publicDir)
  .filter((f) => !f.endsWith(`${sep}sw.js`) && !f.split(sep).pop().startsWith("."))
  .map((f) => toUrl(publicDir, f, "/"));

// App shell pages (SPEC §12) + metadata routes generated by app/
const pages = ["/", "/plan", "/settings", "/login"];
const metaRoutes = ["/manifest.webmanifest", "/icon.svg", "/apple-icon.png"];

const assets = [...new Set([...nextAssets, ...publicAssets, ...metaRoutes])].sort();
const template = readFileSync(join(root, "scripts", "sw-template.js"), "utf8");
const sw = template
  .replace("__VERSION__", buildId)
  .replace("__PAGES__", JSON.stringify(pages))
  .replace("__ASSETS__", JSON.stringify(assets, null, 2));

writeFileSync(join(publicDir, "sw.js"), sw);
console.log(`sw.js: version ${buildId}, ${pages.length} pages, ${assets.length} assets`);
